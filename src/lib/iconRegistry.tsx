/**
 * 查找图标对象：支持英文 ID、中文名称、别名不区分大小写模糊匹配
 */
export function getIconItem(query: string): IconItem | undefined {
  if (!query) return undefined;
  const clean = query.trim().toLowerCase().replace(/^\[icon:/i, "").replace(/\]$/, "").trim();

  // 1. Exact ID match
  const byId = ICON_LIST.find((item) => item.id.toLowerCase() === clean);
  if (byId) return byId;

  // 2. Exact Name match
  const byName = ICON_LIST.find((item) => item.name.toLowerCase() === clean);
  if (byName) return byName;

  // 3. Alias match
  const byAlias = ICON_LIST.find(
    (item) =>
      item.aliases?.some((a) => a.toLowerCase() === clean || clean.includes(a.toLowerCase()))
  );
  if (byAlias) return byAlias;

  // 4. Fuzzy inclusion in name or id
  const byFuzzy = ICON_LIST.find(
    (item) => item.name.includes(clean) || item.id.includes(clean)
  );
  if (byFuzzy) return byFuzzy;

  return undefined;
}

/**
 * 渲染行内图标 SVG 静态 HTML 字符串
 */
export function renderIconSvg(
  query: string,
  options: { size?: number; className?: string } = {}
): string {
  const { size = 15, className = "doc-inline-icon-svg inline-block align-[-2px]" } = options;
  const item = getIconItem(query);
  const IconComponent = item ? item.icon : Sparkles;

  try {
    return renderToStaticMarkup(
      React.createElement(IconComponent, {
        size,
        style: { width: size, height: size, fontSize: size },
        className,
        "aria-hidden": "true",
      })
    );
  } catch {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${className}"><polygon points="12 2 15.09 8.26 22 9.27 17 14.14 18.18 21.02 12 17.77 5.82 21.02 7 14.14 2 9.27 8.91 8.26 12 2"/></svg>`;
  }
}
