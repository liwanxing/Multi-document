import sanitizeHtml from "sanitize-html";
export function sanitizeMarkup(html: string) {
  return sanitizeHtml(html, {
    allowedTags: [
      ...sanitizeHtml.defaults.allowedTags,
      "img",
      "video",
      "source",
      "sup",
      "sub",
      "input",
      "mark",
      "kbd",
      "span",
      "svg",
      "path",
      "circle",
      "rect",
      "line",
      "polyline",
      "polygon",
      "g",
      "del",
      "s",
      "strike",
      "button",
    ],
    allowedAttributes: {
      "*": ["class", "id", "style", "title", "aria-hidden", "data-*"],
      button: ["type", "disabled", "aria-label", "title", "data-*"],
      video: ["src", "controls", "preload", "poster", "width", "height"],
      source: ["src", "type"],
      a: ["href", "title", "target", "rel"],
      img: ["src", "alt", "title", "width", "height"],
      input: ["type", "checked", "disabled"],
      th: ["align"],
      td: ["align"],
      svg: [
        "xmlns",
        "width",
        "height",
        "viewbox",
        "viewBox",
        "fill",
        "stroke",
        "stroke-width",
        "stroke-linecap",
        "stroke-linejoin",
        "aria-hidden",
      ],
      path: ["d", "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin"],
      circle: ["cx", "cy", "r", "fill", "stroke", "stroke-width"],
      rect: ["x", "y", "width", "height", "rx", "ry", "fill", "stroke", "stroke-width"],
      line: ["x1", "y1", "x2", "y2", "stroke", "stroke-width", "stroke-linecap"],
      polyline: ["points", "stroke", "fill", "stroke-width", "stroke-linecap", "stroke-linejoin"],
      polygon: ["points", "stroke", "fill"],
      g: ["fill", "stroke"],
    },
    allowedStyles: {
      "*": {
        width: [/^(auto|\d+(\.\d+)?(px|%)?)$/],
        height: [/^(auto|\d+(\.\d+)?(px|%)?)$/],
        "font-size": [/^\d+(\.\d+)?(px|rem|em|%)$/],
        "max-width": [/^\d+(px|%)$/],
        color: [/^#[a-fA-F0-9]{3,8}$/, /^[a-z]+$/],
        "background-color": [/^#[a-fA-F0-9]{3,8}$/, /^[a-z]+$/, /^transparent$/],
        padding: [/^[\d .]+(px|rem|em|%)$/],
        "border-radius": [/^\d+(px|%)$/],
        "text-decoration": [/^[\w\s-]+$/],
      },
    },
    allowedSchemes: ["http", "https", "mailto"],
    allowedSchemesByTag: { img: ["http", "https", "data"] },
    transformTags: {
      video: sanitizeHtml.simpleTransform("video", {
        controls: "controls",
        preload: "metadata",
      }),
      a: sanitizeHtml.simpleTransform("a", { rel: "noopener noreferrer" }),
      input: sanitizeHtml.simpleTransform("input", {
        type: "checkbox",
        disabled: "disabled",
      }),
    },
    exclusiveFilter: (frame) =>
      frame.tag === "img" &&
      !!frame.attribs.src?.startsWith("data:") &&
      !/^data:image\/(png|jpeg|gif|webp);base64,/i.test(frame.attribs.src),
  });
}
